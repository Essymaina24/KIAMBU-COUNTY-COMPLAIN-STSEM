-- KCC Complaint Management System - Supabase PostgreSQL setup
-- Safe to run more than once. Does not drop or truncate existing data.

CREATE TABLE IF NOT EXISTS departments (
  dept_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  dept_name VARCHAR(100) NOT NULL UNIQUE,
  description TEXT,
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS categories (
  category_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category_name VARCHAR(80) NOT NULL UNIQUE,
  dept_id INTEGER NOT NULL REFERENCES departments(dept_id),
  resolution_days INTEGER NOT NULL DEFAULT 14,
  description TEXT
);

CREATE TABLE IF NOT EXISTS users (
  user_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  email VARCHAR(150) NOT NULL UNIQUE,
  phone VARCHAR(20),
  password_hash TEXT NOT NULL,
  role VARCHAR(20) NOT NULL DEFAULT 'citizen'
    CHECK (role IN ('citizen','officer','supervisor','admin')),
  dept_id INTEGER REFERENCES departments(dept_id),
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS complaints (
  complaint_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reference_no VARCHAR(20) NOT NULL UNIQUE,
  citizen_id INTEGER,
  citizen_name VARCHAR(100) NOT NULL,
  citizen_contact VARCHAR(150) NOT NULL,
  category_id INTEGER NOT NULL REFERENCES categories(category_id),
  dept_id INTEGER NOT NULL REFERENCES departments(dept_id),
  location VARCHAR(200) NOT NULL,
  description TEXT NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'submitted'
    CHECK (status IN ('submitted','under_review','in_progress','resolved','closed')),
  is_duplicate_flag BOOLEAN NOT NULL DEFAULT FALSE,
  submitted_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  last_updated_at TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS complaint_updates (
  update_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  complaint_id INTEGER NOT NULL REFERENCES complaints(complaint_id),
  officer_id INTEGER NOT NULL REFERENCES users(user_id),
  new_status VARCHAR(20) NOT NULL
    CHECK (new_status IN ('submitted','under_review','in_progress','resolved','closed')),
  notes TEXT NOT NULL,
  escalated BOOLEAN NOT NULL DEFAULT FALSE,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS escalations (
  escalation_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  complaint_id INTEGER NOT NULL REFERENCES complaints(complaint_id),
  notified_supervisor INTEGER NOT NULL REFERENCES users(user_id),
  days_overdue INTEGER NOT NULL,
  resolved BOOLEAN NOT NULL DEFAULT FALSE,
  escalated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_complaints_reference ON complaints(reference_no);
CREATE INDEX IF NOT EXISTS idx_complaints_status ON complaints(status);
CREATE INDEX IF NOT EXISTS idx_complaints_department ON complaints(dept_id);
CREATE INDEX IF NOT EXISTS idx_updates_complaint ON complaint_updates(complaint_id);

